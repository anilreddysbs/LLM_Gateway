"""OpenAI-compatible request and response schemas for Chat Completions."""

import time
import uuid
from typing import Literal

from pydantic import BaseModel, Field


class ChatMessage(BaseModel):
    """A single chat message with a role and string content."""

    role: Literal["system", "user", "assistant", "function", "tool"] = Field(
        ...,
        description="The role of the author of this message.",
    )
    content: str = Field(..., description="The contents of the message.")
    name: str | None = Field(None, description="Optional name of the participant.")


class ChatCompletionRequest(BaseModel):
    """Standard OpenAI Chat Completions API request payload."""

    model: str = Field(
        ...,
        description="ID of the model to use, or a configured gateway routing alias.",
    )
    messages: list[ChatMessage] = Field(
        ...,
        min_length=1,
        description="A list of messages comprising the conversation so far.",
    )
    temperature: float | None = Field(
        default=1.0,
        ge=0.0,
        le=2.0,
        description="Sampling temperature between 0 and 2.",
    )
    max_tokens: int | None = Field(
        default=None,
        ge=1,
        description="Maximum number of tokens to generate.",
    )
    stream: bool = Field(
        default=False,
        description="If set, partial message deltas will be sent as SSE events.",
    )
    user: str | None = Field(
        default=None,
        description="A unique identifier representing your end-user.",
    )


class UsageInfo(BaseModel):
    """Token usage metrics for the completion."""

    prompt_tokens: int = Field(default=0, description="Tokens in the prompt.")
    completion_tokens: int = Field(default=0, description="Tokens in the generated response.")
    total_tokens: int = Field(default=0, description="Total tokens used.")


class ChatChoiceMessage(BaseModel):
    """The generated chat message returned in the choice."""

    role: Literal["assistant"] = "assistant"
    content: str = ""


class ChatChoice(BaseModel):
    """A completion choice generated by the model."""

    index: int = 0
    message: ChatChoiceMessage
    finish_reason: str | None = "stop"


class ChatCompletionResponse(BaseModel):
    """OpenAI-compatible response payload for non-streaming completions."""

    id: str = Field(default_factory=lambda: f"chatcmpl-{uuid.uuid4().hex[:12]}")
    object: Literal["chat.completion"] = "chat.completion"
    created: int = Field(default_factory=lambda: int(time.time()))
    model: str
    choices: list[ChatChoice]
    usage: UsageInfo


class ChatCompletionChunkDelta(BaseModel):
    """The partial delta update for a streaming completion chunk."""

    role: str | None = None
    content: str | None = None


class ChatCompletionChunkChoice(BaseModel):
    """Choice representation within a streaming chunk."""

    index: int = 0
    delta: ChatCompletionChunkDelta
    finish_reason: str | None = None


class ChatCompletionChunk(BaseModel):
    """OpenAI-compatible Server-Sent Event chunk payload."""

    id: str = Field(default_factory=lambda: f"chatcmpl-{uuid.uuid4().hex[:12]}")
    object: Literal["chat.completion.chunk"] = "chat.completion.chunk"
    created: int = Field(default_factory=lambda: int(time.time()))
    model: str
    choices: list[ChatCompletionChunkChoice]
    usage: UsageInfo | None = None
